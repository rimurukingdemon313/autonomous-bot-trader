_MASKS: dict[str, np.ndarray] = {
    ch: np.array([[(row >> (W - 1 - x)) & 1 for x in range(W)] for row in rows], dtype=bool)
    for ch, rows in GLYPHS.items()
}


def mask(text: str, scale: int = 2) -> np.ndarray:
    """The text as a boolean pixel mask, one pixel of space between glyphs (both scaled)."""
    text = text.upper()
    if not text:
        return np.zeros((H * scale, 0), dtype=bool)
    cols = []
    for i, ch in enumerate(text):
        g = _MASKS.get(ch, _MASKS["?"])
        cols.append(g)
        if i < len(text) - 1:
            cols.append(np.zeros((H, 1), dtype=bool))
    m = np.concatenate(cols, axis=1)
    return np.kron(m, np.ones((scale, scale), dtype=bool)).astype(bool)


def width(text: str, scale: int = 2) -> int:
    return 0 if not text else (len(text) * (W + 1) - 1) * scale
