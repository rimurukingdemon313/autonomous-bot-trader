def _artifact(name: str) -> dict:
    p = ROOT / "research" / "knowledge" / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else {}


def _get(d: Any, *keys: str) -> Any:
    for k in keys:
        if not isinstance(d, dict):
            return None
        d = d.get(k)
    return d


