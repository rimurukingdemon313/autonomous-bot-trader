def strict_status_of_edge(edge_id: str, cur: dict) -> tuple[str, list[str]]:
    c = cur.get(edge_id)
    if c is None:
        return "FAILED", ["rejected by its program"]
    if edge_id == "RV-1":
        return "FAILED", c["notes"]
    # A preregistered robustness gate it failed (anything but significance, which the strict t gate judges
    # again) is a failure, whatever the edge registry called it.
    robust = [g for g in c.get("failed_preregistered_gates", []) if g != "t"]
    if robust:
        return "FAILED", [f"failed its preregistered gates: {', '.join(robust)}"]
    return promotion.status(c["evidence"])


