def _git(*args) -> str:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _sha(paths) -> str:
    h = hashlib.sha256()
    for p in paths:
        h.update(p.read_bytes())
    return h.hexdigest()[:16]


def _tests() -> dict:
    r = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider", "tests"],
                       cwd=ROOT, capture_output=True, text=True)
    m = re.search(r"(\d+) tests? collected", r.stdout)
    per_file = [int(x) for x in re.findall(r"^tests/\S+: (\d+)$", r.stdout, flags=re.M)]
    n = int(m.group(1)) if m else (sum(per_file) if per_file else None)
    return {"collected": n, "command": "python -m pytest tests"}


def _mutation() -> dict:
    p = ROOT / "docs" / "MUTATION_AUDIT.md"
    m = re.search(r"\*\*(\d+) of (\d+) killed\.\*\*", p.read_text()) if p.exists() else None
    return {"killed": int(m.group(1)), "total": int(m.group(2)), "command": "python scripts/mutation_audit.py"} \
        if m else {"killed": None, "total": None}


def build(with_tests: bool = True) -> dict:
    rows = [json.loads(line) for line in (ROOT / "research" / "registry.jsonl").read_text().splitlines() if line.strip()]
    trials = {r["id"]: r for r in rows if r["kind"] == "trial"}
    verdicts = {r["trial"]: r for r in rows if r["kind"] == "verdict"}
    cur = curated_evidence()
    experiments = []
    for tid, t in trials.items():
        v = verdicts.get(tid)
        raw = (v or {}).get("status") or t.get("status")
        if tid in ("RV-1",):
            st, why = "FAILED", cur["RV-1"]["notes"]
        elif tid in ("DIV-2", "DIV-2-H"):
            st, why = strict_status_of_edge("DIV2-H1-TSMOM12", cur)
        elif tid == "RC-EQ2-H":
            st, why = strict_status_of_edge("RCEQ-E1-TOM", cur)
        elif v is None and raw == "PENDING":
            st, why = "REGISTERED", ["no verdict (descriptive or forward-only)" if t.get("tests") == 0 or tid == "TOM-F"
                                     else "no verdict"]
        elif raw in ("FAILED", "ABANDONED", "INCONCLUSIVE"):
            st, why = "FAILED", [f"registry verdict {raw}"]
        else:
            st, why = "FAILED", [f"registry verdict {raw}: not examined against the strict gates"]
        experiments.append({
            "experiment_id": tid, "title": t.get("title"), "hypothesis": t.get("hypothesis"),
            "preregistration": t.get("preregistration"), "registered": t.get("registered"),
            "uses": t.get("uses"), "tests": t.get("tests"), "configurations": t.get("configurations"),
            "design": t.get("design"), "registry_verdict": raw, "status": st, "status_reasons": why,
            "artifact": (v or {}).get("result", {}).get("artifact"),
            "artifact_sha256": (v or {}).get("result", {}).get("artifact_sha256"),
        })
    edges = json.loads((ROOT / "research" / "knowledge" / "edge_registry.json").read_text())["edges"]
    edge_rows = []
    for e in edges:
        st, why = strict_status_of_edge(e["edge_id"], cur) if e["edge_id"] in cur else \
            ("FAILED", [f"edge registry {e['status']}: " + ", ".join(e.get("failed_checks") or [])])
        edge_rows.append({"edge_id": e["edge_id"], "program": e["program"], "registry_status": e["status"],
                          "status": st, "reasons": why, "net_expectancy": e.get("net_expectancy"),
                          "t_stat": e.get("t_stat"), "sample_size": e.get("sample_size"), "source": e.get("source")})
    dq_path = ROOT / "research" / "results" / "data_quality.json"
    dq = json.loads(dq_path.read_text()) if dq_path.exists() else {}
    holdouts = []
    for p in sorted((ROOT / "research").glob("holdout*.json")):
        h = json.loads(p.read_text())
        touching = [x for x in experiments
                    if any(u.get("universe") == h["universe"] and str(u.get("end") or "9999") > h["start"][:10]
                           and str(u.get("start", "")) >= h["start"][:10] for u in (x.get("uses") or []))]
        opened = [x["experiment_id"] for x in touching if str(x.get("registered") or "") >= h["sealed_at"]]
        prior = [x["experiment_id"] for x in touching if str(x.get("registered") or "") < h["sealed_at"]]
        holdouts.append({"file": str(p.relative_to(ROOT)), "universe": h["universe"], "start": h["start"],
                         "sealed_at": h["sealed_at"], "opened_by": opened, "exposure_before_seal": prior,
                         "state": "OPENED" if opened else "SEALED"})
    validated = [e for e in edge_rows if e["status"] == "VALIDATED"]
    promising = [e for e in edge_rows if e["status"] in ("PROMISING", "FORWARD_TESTING", "ELIGIBLE_FOR_REVIEW")]
    counts = {s: sum(1 for x in experiments if x["status"] == s) for s in promotion.STATUSES}
    edge_counts = {s: sum(1 for x in edge_rows if x["status"] == s) for s in promotion.STATUSES}
    # The final status says whether anything PASSED: a PROMISING lead has not, so it is still NO EDGE
    # (with the leads listed under promising_edges).
    eligible = [e for e in edge_rows if e["status"] == "ELIGIBLE_FOR_REVIEW"]
    final = "VALIDATED" if validated else ("ELIGIBLE FOR REVIEW" if eligible else "NO EDGE")
    return {
        "status_version": STATUS_VERSION, "promotion_version": promotion.PROMOTION_VERSION,
        "code_commit": _git("rev-parse", "HEAD"),
        "data_version": "bars-" + _sha(sorted((ROOT / "data").glob("*manifest*.json")) +
                                       sorted((ROOT / "data" / "m5").glob("manifest_*.json"))),
        "cost_model_version": {
            "research_h1": "labels.CostModel: measured bid/ask, 0.1 pip slippage per fill, 0.7 pip commission, "
                           "swap 0.05 x ATR24(H1) per night either side",
            "intraday": "intraday.Costs (id-1.0.0): measured bid/ask, 0.1 pip slippage, 0.7 pip commission, BIS financing "
                        "per 21:00 UTC rollover (Wednesday x3) with 1.5% markup",
            "retail_cfd": "retail.py / rc.py: spread, slippage, overnight markup, dividends (RC programs)",
            "paper_broker": "paper-1.1.0: live bid/ask + 0.1 pip slippage, $7/lot commission, swap per 21:00 UTC rollover",
            "risk_engine": RISK_VERSION,
            "provisional": "no broker is integrated (PAPER only; MetaTrader 5 planned): every research cost is "
                           "provisional against the broker that will eventually be used",
        },
        "generated_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "final_status": final,
        "final_statement": ("NO EDGE — DO NOT TRADE" if final == "NO EDGE" else
                            "ELIGIBLE FOR REVIEW — NOT VALIDATED, DO NOT TRADE" if final == "ELIGIBLE FOR REVIEW" else final),
        "experiment_counts": counts, "edge_counts": edge_counts,
        "experiments": experiments,
        "strategies": [
            {"strategy": "evidence (analogue synthesis, PR-001 system)", "status": "FAILED",
             "reason": "PR-001 FAILED: -0.07R per trade after costs, t -2.9 (2010-2016)", "route": "PAPER only"},
            {"strategy": "llm_trader / trading_room / experimental_ai (a language model proposes)", "status": "PROPOSED",
             "reason": "never backtestable; no forward evidence of value", "route": "SHADOW in every mode (takeover audit)"},
            {"strategy": "edges (promoted edges only)", "status": "REGISTERED",
             "reason": "models/artifacts/promoted_edges.json absent: nothing promoted", "route": "nothing to trade"},
            {"strategy": "turn-of-the-month on index CFDs (RCEQ-E1-TOM)",
             "status": strict_status_of_edge("RCEQ-E1-TOM", cur)[0],
             "reason": "research only; not implemented in the bot; see promising_edges", "route": "not implemented"},
            {"strategy": "ID-2 intraday opportunity engine", "status": "FAILED",
             "reason": "0 of 30 tests promoted on development 2011-2013", "route": "research only"},
        ],
        "validated_edges": validated,
        "promising_edges": [{**e, "curated": cur.get(e["edge_id"])} for e in promising],
        "failed_edges": [{"edge_id": e["edge_id"], "program": e["program"], "reasons": e["reasons"][:3]}
                         for e in edge_rows if e["status"] == "FAILED"],
        "sealed_periods": holdouts,
        "known_data_defects": [
            {"defect": "00:00-00:59 UTC missing", "files": dq.get("hour00_missing_files"),
             "measured_bias_r": (dq.get("hour00_sensitivity") or {}).get("max_abs_difference_r"),
             "rerun": "impossible here: no source with the hour is reachable (docs/DATA_QUALITY_REPORT.md)"},
            {"defect": "index-CFD bid/ask history only from 2012 (Dukascopy datafeed), sparse quoting in 2012-2013",
             "files": "data/ix/", "measured_bias_r": None,
             "rerun": "IX programs use 2012+; days without a quote are skipped, never filled"},
        ],
        "known_research_limitations": [
            "no broker is integrated (PAPER only): real spreads, commission and swaps of the eventual broker are "
            "unmeasured; all costs are provisional",
            "index-CFD spreads are roughly constant in points, so their cost in bp fell 3-5x from 2013 to 2020 as the "
            "indices rose: results from early years overstate today's cost",
            "FX bid/ask history is 2007-2016 for research (2017+ sealed); about 10 years, one source",
            "a language model cannot be backtested (training data contains the outcomes): its value is forward-only",
            "every rejected hypothesis was judged on overlapping FX data; thresholds count prior tests (registry)",
            "the forward ledger has no resolved EVALUATION outcomes in this repository: no forward evidence exists",
        ],
        "risk_policy": {"live_risk_pct": 0.0, "max_risk_per_trade_pct_while_unvalidated": UNVALIDATED_MAX_RISK_PCT,
                        "experimental_execute": "refused", "model_originated_trades": "SHADOW",
                        "llm_veto": "advisory only (recorded as would_veto for the A/B comparison)"},
        "tests": _tests() if with_tests else None,
        "mutation_audit": _mutation(),
    }


def headline(st: dict) -> str:
    c, e = st["experiment_counts"], st["edge_counts"]
    tom = next((p for p in st["promising_edges"] if p["edge_id"] == "RCEQ-E1-TOM"), None)
    lines = [
        BEGIN,
        f"> **Canonical status ({st['status_version']}, from `research_status.json`): {st['final_statement']}.**",
        f"> - Experiments: {len(st['experiments'])} registered; "
        + ", ".join(f"{k} {c[k]}" for k in promotion.STATUSES if c.get(k)) + ".",
        f"> - Edges: {sum(e.values())} recorded; " + ", ".join(f"{k} {e[k]}" for k in promotion.STATUSES if e.get(k))
        + ". VALIDATED requires every gate in `aitrader/research/promotion.py`; none passes.",
    ]
    if tom:
        lines.append("> - The one PROMISING lead (not a pass), turn-of-the-month on index CFDs, is **unattractive and decayed**: "
                     "about 1.9% a year at t 2.18 with a 23% drawdown, t 0.46 since 2021, t 0.64 at doubled costs. "
                     "It is not implemented.")
    lines += [
        f"> - Live trading is impossible; DEMO sends no order (nothing is validated); per-trade risk is capped at "
        f"{st['risk_policy']['max_risk_per_trade_pct_while_unvalidated']}%. Language-model trades are shadow only.",
        f"> - Tests collected: {(st.get('tests') or {}).get('collected')}; mutation audit: "
        f"{st['mutation_audit'].get('killed')} of {st['mutation_audit'].get('total')} killed. "
        "Numbers in older reports are snapshots of their date.",
        "> - Defects, patches, tests and the strategy-by-strategy record: docs/TAKEOVER_AUDIT.md.",
        END,
    ]
    return "\n".join(lines)


def write_readme(st: dict) -> str:
    text = README.read_text()
    block = headline(st)
    if BEGIN in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        return text[:a] + block + text[b:]
    first = text.index("\n> **Status:")
    return text[:first] + "\n" + block + "\n>" + text[first:]


def _stable(st: dict) -> dict:
    return {k: v for k, v in st.items() if k not in ("generated_at_utc", "code_commit")}


def main() -> int:
    check = "--check" in sys.argv
    st = build(with_tests=True)
    if check:
        old = json.loads(OUT.read_text()) if OUT.exists() else {}
        stale_json = _stable(old) != _stable(st)
        stale_readme = headline(old) not in README.read_text() if old else True
        print(json.dumps({"research_status_stale": stale_json, "readme_stale": stale_readme}))
        return 1 if (stale_json or stale_readme) else 0
    OUT.write_text(json.dumps(st, indent=1, sort_keys=True, default=str) + "\n")
    README.write_text(write_readme(st))
    print(json.dumps({"final": st["final_statement"], "experiments": st["experiment_counts"],
                      "edges": st["edge_counts"]}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
