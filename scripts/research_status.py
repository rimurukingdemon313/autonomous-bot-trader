"""The canonical research status (takeover audit, step 3).

    python scripts/research_status.py          # -> research_status.json, and the README's generated headline
    python scripts/research_status.py --check  # exit 1 if either is stale (CI / tests)

Every headline number in the README comes from research_status.json, which is built here from what is
committed:

- the research registry (research/registry.jsonl);
- the program artifacts (research/knowledge/*.json);
- the holdout seals;
- the data-quality report;
- the mutation audit;
- the test collection.

Statuses are the strict ones of aitrader/research/promotion.py; a registry PASSED is never copied as
VALIDATED. Curated evidence below cites, for every number, the artifact and key it comes from.
"""

